 fun seeds(language: String): List<Seed> = seeds[if(language.startsWith("pt-")) "pt" else language] ?: error("No draft for $language")
 fun puzzles(language: String): List<Puzzle> {
  require(language in locales)
  return seeds(language).mapIndexed { i,s -> Crossword.generate("$language-${i+1}",s.letters,s.targets.split(' '),emptySet(),s.difficulty,i/4,811+i) }
 }
